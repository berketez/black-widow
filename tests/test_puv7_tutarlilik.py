    assert [(y.ad, y.ifn, y.tfn) for y in u.yontemler] == [
        ("Ad", b["girisler"][F_PT_AD], b["girisler"][F_T_AD])]
    assert tv.tip_adi(b["tipler"]["T"]) == "p.T"        # ExtraStar: baştaki * atılır


