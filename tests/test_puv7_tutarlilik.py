@pytest.mark.parametrize("surum", SURUMLER)
def test_temiz_modul_damgalari(surum: str) -> None:
    g, b = kur(surum)
    s = T.denetle(g)
    assert s.durum == "calisti"
    beklenen = {
        F_GOGO: T.DAMGA_CIFT_KAYNAK,      # T5
        F_T_AD: T.DAMGA_CIFT_KAYNAK,      # T2 (yapının yöntem tablosu)
        F_PT_AD: T.DAMGA_CIFT_KAYNAK,     # T1 + T2
        F_EKLE: T.DAMGA_CIFT_KAYNAK,      # tip parametreli alıcı
        F_CALIS: T.DAMGA_CIFT_KAYNAK,     # kaçışlı paket yolu
        F_UNREACH: T.DAMGA_TEK_KAYNAK,    # budanmış yöntem yer tutucusu dışlanır
        F_YAZ: T.DAMGA_CIFT_KAYNAK,       # yalnız ikinci itab (T1)
        F_YARDIM: T.DAMGA_TEK_KAYNAK,
    }
    assert {i: _damga(s, b, i) for i in beklenen} == beklenen
    assert s.ozet["guclu_isaretli_fonksiyon"] == 0
    assert s.ozet["T1"] == {"itab": 4, "bakilan_yuva": 4, "uyan": 4, "kapsanan_fonksiyon": 4}
    assert s.ozet["T2"]["bakilan"] == s.ozet["T2"]["uyan"] == 8
    assert s.ozet["T2"]["paket_bakilan"] == s.ozet["T2"]["paket_uyan"] == 8
    assert s.ozet["T5"] == {"bakilan": 1, "uyan": 1, "sarmalayici_kimligi": 23, "tam_ad_tablosu": True}
    assert s.karar == T.KARAR_TEMIZ


