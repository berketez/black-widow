GO_METIN = 0x100001000
PCLN = 0x100100000
MODUL = 0x100200000
FFTAB = 0x100210000
BINFO = 0x100220000
TIPLER = 0x100300000
ITABVERI = 0x100400000      # 1.26: itab'ların durduğu veri bölümü
ITABLINK = 0x100410000
TYPELINK = 0x100420000
BOZUK_HAM = 0x8000_0000_DEAD_BEEF
ANA = "example.com/uyg"
BOY = 0x40

# Fonksiyonlar (sıra sabit; testler adla değil sırayla değiştirir).
F_GOGO, F_T_AD, F_PT_AD, F_EKLE, F_CALIS, F_UNREACH, F_YAZ, F_YARDIM = range(8)
FONKSIYONLAR = [
    # (ad, funcID, dosya)
    ("runtime.gogo", 9, "/go/src/runtime/asm_arm64.s"),
    (f"{ANA}/p.T.Ad", 0, f"{ANA}/p/t.go"),
    (f"{ANA}/p.(*T).Ad", 23, "<autogenerated>"),
    (f"{ANA}/p.(*Liste[go.shape.int]).Ekle", 0, f"{ANA}/p/liste.go"),
    (f"{ANA}/a%2eb.F.Calis", 0, f"{ANA}/a.b/f.go"),
    ("runtime.unreachableMethod", 0, "/go/src/runtime/iface.go"),
    (f"{ANA}/p.(*U).Yaz", 0, f"{ANA}/p/u.go"),
    (f"{ANA}/p.yardim", 0, f"{ANA}/p/t.go"),
]


def _zz(v: int) -> int:
    return 2 * v if v >= 0 else -2 * v - 1


def _uv(v: int) -> bytes:
    out = bytearray()
    while True:
        b = v & 0x7F
        v >>= 7
        if v:
            out.append(b | 0x80)
        else:
            out.append(b)
            return bytes(out)


def _pc_tablo(ciftler: list[tuple[int, int]], min_lc: int = 4) -> bytes:
    out = bytearray()
    onceki = -1
    for deger, uzunluk in ciftler:
        out += _uv(_zz(deger - onceki))
        out += _uv(uzunluk // min_lc)
        onceki = deger
    out += b"\0"
    return bytes(out)


def _buildinfo(surum: str) -> bytes:
    mod = (f"path\t{ANA}/cmd/uyg\nmod\t{ANA}\tv1.2.3\th1:abc=\n").encode()
    mod = b"\x30" * 16 + mod + b"\x31" * 16
    b = bytearray(G.BUILDINFO_IMZA + bytes([8, 2]) + b"\0" * 16)
    b += _uv(len(surum)) + surum.encode() + _uv(len(mod)) + mod
    return bytes(b)


class _Bolge:
    """Sabit tabanlı bayt bölgesi; göstericiler düzeltme sözlüğüne yazılır."""

    def __init__(self, taban: int, rk: dict) -> None:
        self.taban = taban
        self.b = bytearray(b"\0" * 16)   # ofset 0 = "ad yok"
        self.rk = rk

    def hizala(self, n: int = 8) -> None:
        self.b += b"\0" * ((-len(self.b)) % n)

    def adres(self) -> int:
        return self.taban + len(self.b)

    def ad(self, s: str) -> int:
        """Kodlanmış ad; ``types``'a göre ofset döner."""
        off = len(self.b)
        e = s.encode()
        self.b += bytes([0]) + _uv(len(e)) + e
        return off

    def yer(self, n: int) -> int:
        self.hizala(8)
        a = self.adres()
        self.b += b"\0" * n
        return a

    def gosterici(self, adres: int, hedef: int) -> None:
        struct.pack_into("<Q", self.b, adres - self.taban, BOZUK_HAM)
        self.rk[adres] = hedef

    def yaz(self, adres: int, bicim: str, *v) -> None:
        struct.pack_into(bicim, self.b, adres - self.taban, *v)


def kur(
    surum: str = "go1.27.4",
    adlar: dict[int, str] | None = None,
    dosyalar: dict[int, str] | None = None,
    pcsp: dict[int, list[tuple[int, int]]] | None = None,
    ek_duz: int = 0,
    struct_uncommon: bool = True,
    itab_araligi_bozuk: bool = False,
    tip_bolgesi_kes: int | None = None,
) -> tuple[BellekGoruntu, dict]:
    adlar = adlar or {}
    dosyalar = dosyalar or {}
    pcsp = pcsp or {}
    fl = [(adlar.get(i, a), fid, dosyalar.get(i, d)) for i, (a, fid, d) in enumerate(FONKSIYONLAR)]
    fl += [(f"{ANA}/p.ek{i}", 0, f"{ANA}/p/t.go") for i in range(ek_duz)]
    n = len(fl)
    girisler = [BOY * i for i in range(n)]
    son = BOY * n
    gabs = [GO_METIN + g for g in girisler]

    # --- pclntab ---------------------------------------------------------
    fn = bytearray(b"ilk\0")
    name_off = []
    for a, _fid, _d in fl:
        name_off.append(len(fn))
        fn += a.encode("utf-8", "surrogateescape") + b"\0"
    ft = bytearray(b"\0")
    dosya_off: dict[str, int] = {}
    for _a, _fid, d in fl:
        if d not in dosya_off:
            dosya_off[d] = len(ft)
            ft += d.encode() + b"\0"
    dosya_sira = {d: i for i, d in enumerate(dosya_off)}
    cutab = b"".join(struct.pack("<I", o) for o in dosya_off.values())
    pct = bytearray(b"\0")
    pcsp_off, pcfile_off = [], []
    for i, (_a, _fid, d) in enumerate(fl):
        pcsp_off.append(len(pct))
        pct += _pc_tablo(pcsp.get(i, [(0, BOY)]))
        pcfile_off.append(len(pct))
        pct += _pc_tablo([(dosya_sira[d], BOY)])
    funcname_off = G.PCHEADER_BOYU
    cu_off = funcname_off + len(fn)
    filetab_off = cu_off + len(cutab)
    pctab_off = filetab_off + len(ft)
    pcln_off = pctab_off + len(pct)
    ftab_boy = 8 * (n + 1)
    funcs = bytearray()
    ftab = bytearray()
    for i, (_a, fid, _d) in enumerate(fl):
        ftab += struct.pack("<II", girisler[i], ftab_boy + len(funcs))
        funcs += struct.pack("<IiiIIIIIIiBBBB", girisler[i], name_off[i], 0, 0, pcsp_off[i],
                             pcfile_off[i], 0, 0, 0, 10 + i, fid, 0, 0, 0)
    ftab += struct.pack("<II", son, 0)
    pclntable = bytes(ftab + funcs)
    baslik = struct.pack("<IBBBBQQQQQQQQ", G.MAGIC_120, 0, 0, 4, 8, n, len(dosya_off), 0,
                         funcname_off, cu_off, filetab_off, pctab_off, pcln_off)
    pclntab = baslik + bytes(fn) + cutab + bytes(ft) + bytes(pct) + pclntable

    # --- findfunctab -----------------------------------------------------
    minpc, maxpc = gabs[0], GO_METIN + son
    nb = (maxpc - minpc + G.FUNC_TAB_KOVA - 1) // G.FUNC_TAB_KOVA
    fft = bytearray()
    for kb in range(nb):
        def ind(pc: int) -> int:
            return max(i for i, g in enumerate(gabs) if g <= pc)
        idx = ind(minpc + kb * G.FUNC_TAB_KOVA)
        alt = [ind(min(minpc + kb * G.FUNC_TAB_KOVA + s * 256, gabs[-1])) - idx for s in range(16)]
        fft += struct.pack("<I16B", idx, *alt)

    # --- tip bölgesi -----------------------------------------------------
    rk: dict[int, int] = {}
    tb = _Bolge(TIPLER, rk)
    yeni = GT.kucuk_surum(surum) is not None and GT.kucuk_surum(surum) >= 27

    def metin(i: int) -> int:
        return girisler[i]

    def tip(kind: int, ad_off: int, tflag: int, ek: int) -> int:
        a = tb.yer(GT.TIP_BOYU + ek)
        tb.yaz(a, "<QQIBBBBQQii", 8, 0, 0, tflag, 8, 8, kind, 0, 0, ad_off, 0)
        return a

    def uncommon(t: int, ofset: int, paket: str, yontemler: list[tuple[str, int, int]]) -> None:
        # yöntemler UncommonType'ın hemen ardında (Moff = 16)
        u = t + ofset
        tb.yaz(u, "<iHHII", tb.ad(paket), len(yontemler), len(yontemler), GT.UNCOMMON_BOYU, 0)
        for j, (yad, ifn, tfn) in enumerate(yontemler):
            tb.yaz(u + GT.UNCOMMON_BOYU + GT.YONTEM_BOYU * j, "<iiii", tb.ad(yad), 0, ifn, tfn)

    def yontem_yeri(n_y: int) -> int:
        return GT.UNCOMMON_BOYU + GT.YONTEM_BOYU * n_y

    u_ofs = GT.UNCOMMON_OFSETI
    # T (yapı): Ad → Ifn (*T).Ad, Tfn T.Ad
    t_t = tip(GT.KIND_STRUCT, tb.ad("*p.T"),
              (GT.TFLAG_UNCOMMON if struct_uncommon else 0) | GT.TFLAG_EXTRA_STAR,
              u_ofs[GT.KIND_STRUCT] - GT.TIP_BOYU + yontem_yeri(1))
    if struct_uncommon:
        uncommon(t_t, u_ofs[GT.KIND_STRUCT], f"{ANA}/p", [("Ad", metin(F_PT_AD), metin(F_T_AD))])
    # *T: Ad + budanmış Gizli (−1)
    t_pt = tip(GT.KIND_POINTER, tb.ad("*p.T"), GT.TFLAG_UNCOMMON,
               u_ofs[GT.KIND_POINTER] - GT.TIP_BOYU + yontem_yeri(2))
    tb.gosterici(t_pt + GT.GOSTERICI_OGESI, t_t)
    uncommon(t_pt, u_ofs[GT.KIND_POINTER], f"{ANA}/p",
             [("Ad", metin(F_PT_AD), metin(F_PT_AD)), ("Gizli", -1, -1)])
    tb.yaz(t_t + 44, "<i", t_pt - TIPLER)          # T.PtrToThis → *T
    # *Liste[int]
    t_pl = tip(GT.KIND_POINTER, tb.ad("*p.Liste[int]"), GT.TFLAG_UNCOMMON,
               u_ofs[GT.KIND_POINTER] - GT.TIP_BOYU + yontem_yeri(1))
    uncommon(t_pl, u_ofs[GT.KIND_POINTER], f"{ANA}/p", [("Ekle", metin(F_EKLE), metin(F_EKLE))])
    # F (yapı) kaçışlı paket yolu
    t_f = tip(GT.KIND_STRUCT, tb.ad("ab.F"), GT.TFLAG_UNCOMMON,
              u_ofs[GT.KIND_STRUCT] - GT.TIP_BOYU + yontem_yeri(1))
    uncommon(t_f, u_ofs[GT.KIND_STRUCT], f"{ANA}/a.b", [("Calis", metin(F_CALIS), metin(F_CALIS))])
    # U (yapı, yöntem tablosu yok) ve *U
    t_u = tip(GT.KIND_STRUCT, tb.ad("p.U"), 0, u_ofs[GT.KIND_STRUCT] - GT.TIP_BOYU)
    t_pu = tip(GT.KIND_POINTER, tb.ad("*p.U"), 0, u_ofs[GT.KIND_POINTER] - GT.TIP_BOYU)
    tb.gosterici(t_pu + GT.GOSTERICI_OGESI, t_u)

    def arayuz(ad: str, yontemler: list[str]) -> int:
        a = tip(GT.KIND_INTERFACE, tb.ad(ad), 0, u_ofs[GT.KIND_INTERFACE] - GT.TIP_BOYU)
        im = tb.yer(GT.IMETHOD_BOYU * len(yontemler))
        for j, y in enumerate(yontemler):
            tb.yaz(im + GT.IMETHOD_BOYU * j, "<ii", tb.ad(y), 0)
        tb.gosterici(a + GT.ARAYUZ_YONTEM_GOSTERICISI, im)
        tb.yaz(a + GT.ARAYUZ_YONTEM_UZUNLUGU, "<QQ", len(yontemler), len(yontemler))
        return a

    i_i = arayuz("p.I", ["Ad", "Kapat"])
    i_j = arayuz("p.J", ["Yaz"])
    i_e = arayuz("p.E", ["Ekle"])
    i_c = arayuz("p.C", ["Calis"])
    itab_tanim = [
        (i_i, t_pt, [metin(F_PT_AD), metin(F_UNREACH)]),
        (i_j, t_pu, [metin(F_YAZ)]),
        (i_e, t_pl, [metin(F_EKLE)]),
        (i_c, t_f, [metin(F_CALIS)]),
    ]

    def itab_yaz(bolge: _Bolge) -> list[int]:
        bolge.hizala(8)
        out = []
        for inter, typ, fun in itab_tanim:
            a = bolge.yer(GT.ITAB_BASLIK_BOYU + 8 * max(len(fun), 1))
            bolge.gosterici(a, inter)
            bolge.gosterici(a + 8, typ)
            for j, hedef in enumerate(fun):
                bolge.gosterici(a + GT.ITAB_BASLIK_BOYU + 8 * j, GO_METIN + hedef)
            out.append(a)
        return out

    ek_bolumler = []
    if yeni:
        typedesclen = len(tb.b)
        itab_adresleri = itab_yaz(tb)
        itaboffset = itab_adresleri[0] - TIPLER
        itabsize = tb.adres() - itab_adresleri[0]
        if itab_araligi_bozuk:
            itabsize += 0x10000
    else:
        iv = _Bolge(ITABVERI, rk)
        itab_adresleri = itab_yaz(iv)
        il = _Bolge(ITABLINK, rk)
        il.b = bytearray()
        for a in itab_adresleri:
            il.gosterici(il.yer(8), a)
        tl = bytearray()
        for t in (t_t, t_f):
            tl += struct.pack("<i", t - TIPLER)
        ek_bolumler = [("__data", ITABVERI, bytes(iv.b), False),
                       ("__itablink", ITABLINK, bytes(il.b), False),
                       ("__typelink", TYPELINK, bytes(tl), False)]
    tb.hizala(8)
    etypes = tb.adres()
    tip_baytlari = bytes(tb.b)
    if tip_bolgesi_kes is not None:
        tip_baytlari = tip_baytlari[:tip_bolgesi_kes]

    # --- moduledata ------------------------------------------------------
    md = bytearray(8 * 48)
    md_adres = MODUL + 0x40
    uz = {2: len(fn), 3: len(fn), 5: len(cutab) // 4, 6: len(cutab) // 4, 8: len(ft), 9: len(ft),
          11: len(pct), 12: len(pct), 14: len(pclntable), 15: len(pclntable), 17: n + 1, 18: n + 1}
    gos = {0: PCLN, 1: PCLN + funcname_off, 4: PCLN + cu_off, 7: PCLN + filetab_off,
           10: PCLN + pctab_off, 13: PCLN + pcln_off, 16: PCLN + pcln_off, 19: FFTAB,
           20: minpc, 21: maxpc, 22: GO_METIN, 23: GO_METIN + son + 0x100, GT.MD_TYPES: TIPLER}
    if yeni:
        gos[GT.MD_ETYPES_127] = etypes
        uz[GT.MD_TYPEDESCLEN_127] = typedesclen
        uz[GT.MD_ITABOFFSET_127] = itaboffset
        uz[GT.MD_ITABSIZE_127] = itabsize
    else:
        gos[GT.MD_ETYPES_126] = etypes
    for i, v in uz.items():
        struct.pack_into("<Q", md, 8 * i, v)
    for i, v in gos.items():
        struct.pack_into("<Q", md, 8 * i, BOZUK_HAM)
        rk[md_adres + 8 * i] = v
    modul = b"\x11" * 0x40 + bytes(md) + b"\x22" * 0x40

    kod = struct.pack("<I", 0xD503201F) * (son // 4) + b"\0" * 0x100
    bolumler = [
        ("__text", GO_METIN, kod, True),
        ("__gopclntab", PCLN, pclntab, False),
        ("__go_module", MODUL, modul, False),
        ("__noptrdata", FFTAB, bytes(fft), False),
        ("__go_buildinfo", BINFO, _buildinfo(surum), False),
        ("__rodata", TIPLER, tip_baytlari, False),
    ] + ek_bolumler
    g = BellekGoruntu(bolumler, mimari="arm64", yeniden_konumlamalar=rk, fonksiyon_baslangiclari=gabs)
    bilgi = {"girisler": gabs, "tipler": {"T": t_t, "PT": t_pt, "PL": t_pl, "F": t_f, "U": t_u,
                                           "PU": t_pu, "I": i_i}}
    return g, bilgi


def _damga(s: T.TutarlilikSonucu, bilgi: dict, i: int) -> str | None:
    return s.damga(bilgi["girisler"][i])


