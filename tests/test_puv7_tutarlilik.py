@pytest.mark.parametrize("surum", SURUMLER)
def test_tip_okuyucu_itab_ve_tipler(surum: str) -> None:
    g, b = kur(surum)
    p = G.GoPclntab(g)
    tv = GT.GoTipVerisi(g, p, surum)
    assert tv.calisti, tv.neden
    its = tv.itablar()
    assert [len(it.yontemler) for it in its] == [2, 1, 1, 1]
    assert its[0].yontemler[0][0] == "Ad" and its[0].yontemler[1][0] == "Kapat"
    assert its[0].fun == [b["girisler"][F_PT_AD], b["girisler"][F_UNREACH]]
    tipler = tv.ulasilan_tipler(its)
    assert b["tipler"]["T"] in tipler      # *T'nin öğesi
    assert tv.itab_kaynagi == (GT.ITAB_KAYNAGI_TABLO if surum == "go1.27.4" else GT.ITAB_KAYNAGI_ITABLINK)


def test_yapi_uncommon_ofseti_80_ve_extra_star() -> None:
    g, b = kur()
    tv = GT.GoTipVerisi(g, G.GoPclntab(g), "go1.27.4")
    u = tv.uncommon(b["tipler"]["T"])
